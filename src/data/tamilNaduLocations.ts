// Helper to generate 24 hours of realistic 1-hour telemetry history leading up to current hour in Indian Standard Time (IST)
export function generateHourlyHistory(
  baseTemp: number,
  baseTurbidity: number,
  basePh: number,
  baseTds: number,
  baseColiform: number,
  baseRisk: number,
  peakRainfallHour: number = 14,
  rainIntensity: number = 12
): HourlyDataPoint[] {
  const hours: HourlyDataPoint[] = [];
  const nowHour = 22; // Current hour 22:00 IST
  
  for (let i = 23; i >= 0; i--) {
    const h = (nowHour - i + 24) % 24;
    const hhStr = h.toString().padStart(2, "0");
    const hourStr = `${hhStr}:00`;
    
    // Simulate diurnal temperature curve (coolest at 05:00, peak at 14:00)
    const diurnalFactor = Math.sin(((h - 5) / 24) * 2 * Math.PI);
    const temp = Number((baseTemp + diurnalFactor * 3.2 - (i === 0 ? 0 : Math.random() * 0.3)).toFixed(1));
    
    // Rainfall pattern
    const rainDistance = Math.abs(h - peakRainfallHour);
    let rainfall = 0;
    if (rainDistance <= 3) {
      rainfall = Number((Math.max(0, rainIntensity - rainDistance * 3.0) + Math.random() * 1.2).toFixed(1));
    }
    
    // Water turbidity reacts to rainfall with runoff lag
    const runoffBoost = rainfall > 0 ? rainfall * 0.65 : 0;
    const turbidity = Number(Math.max(0.4, (baseTurbidity + runoffBoost - (i > 10 ? 2.0 : 0) + (Math.random() * 0.3 - 0.15))).toFixed(1));
    
    const ph = Number((basePh + (turbidity > 5 ? -0.2 : 0.05) + (Math.random() * 0.08 - 0.04)).toFixed(1));
    const tds = Math.round(baseTds + turbidity * 10 + Math.random() * 12);
    const coliform = Math.max(0, Math.round(baseColiform + (turbidity > 6 ? 10 : 0) + (Math.random() * 2 - 1)));
    const humidity = Math.min(98, Math.round(68 + (rainfall > 0 ? 22 : 0) + (Math.random() * 4 - 2)));
    
    // Risk score calculation
    const riskFactor = Math.min(100, Math.max(5, Math.round(baseRisk + (turbidity > 5 ? 12 : -4) + (coliform > 5 ? 18 : 0))));
    
    hours.push({
      hour: `${hourStr} IST`,
      timestamp: `2026-08-14T${hourStr}:00+05:30`,
      temperature: temp,
      rainfallMm: rainfall,
      humidity,
      turbidity,
      ph,
      tds,
      coliformCount: coliform,
      riskScore: riskFactor,
    });
  }
  return hours;
}

